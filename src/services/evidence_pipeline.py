"""Evidence extraction pipeline (Trust Phase 1 Phase C).

The orchestrator that turns an uploaded document into cited fields
in the evidence substrate. Calls the 6 deterministic extractors and
1 LLM extractor defined inline, persists results via the
EvidenceSubstrateService, and writes cost records to
evidence_extraction_costs for every field.

The pipeline is the only path that produces extracted_fields. UI
surfaces, Q&A, claim verification, and renewal diff all read from
the substrate; they do not call extractors directly. Per motto v3
§0.1 (no parallel paths), there is exactly one pipeline.

Append-only contract: every run produces rows with a fresh
parser_version. Re-running the pipeline on a document does not
delete prior rows. The UI shows the latest row per (document,
field) by created_at; older rows remain for audit.

LLM honesty check: every LLM-extracted field is verified against
the source text before the citation is written. If the structured
output contains a clause that the page text does not contain, the
candidate is rejected and no unverified value enters the substrate.
This is the substrate's defense against the most common LLM failure
mode: citing text that isn't there.
"""
from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Optional, Protocol
from uuid import UUID

from src.models.evidence import (
    ExtractedValue,
    ExtractionCostRecord,
    ParserKind,
    ValueType,
)
from src.security.prompt_injection import fence_untrusted_content
from src.models.extraction import RoomRentCapExtraction
from src.services.evidence_substrate_service import (
    EvidenceSubstrateService,
    EvidenceSubstrateUnavailable,
)

log = logging.getLogger(__name__)


# --- 1. Extractor protocol ---

@dataclass
class ExtractorResult:
    """The shape every extractor returns. The pipeline turns this
    into substrate rows. page_artifact_id is required; the span is
    optional for v1 of the layout parser (which only does
    page-level citation, not span-level)."""

    field_name: str
    value: ExtractedValue
    value_type: ValueType
    confidence: float
    page_artifact_id: UUID
    source_span_id: Optional[UUID] = None
    evidence_strength: float = 1.0
    cite_string: str = ""  # generated by the pipeline if empty


class Extractor(Protocol):
    """An extractor takes a document's pages and returns one or
    more ExtractorResult. Deterministic extractors return 0 or 1
    result (the field is either present or not). LLM extractors
    may return 0 or 1."""

    field_name: str
    parser_kind: ParserKind

    async def extract(
        self, document_id: UUID, page_texts: dict[int, str]
    ) -> Optional[ExtractorResult]: ...


# --- 2. Deterministic extractors ---
# Each is a small, focused regex/lookup. The pattern is the same:
# iterate pages in order, return the first match with the
# strongest evidence.

_POLICY_NUMBER_RE = re.compile(
    r"(?i)policy\s*(?:no|number|#)\s*[:\-]?\s*([A-Z0-9][A-Z0-9\-\/]{4,})"
)
_POLICY_HOLDER_RE = re.compile(
    r"(?im)^\s*(?:policy\s*holder|insured\s*name|name\s*of\s*the\s*insured)"
    r"\s*[:\-]\s*(.+?)\s*$"
)
_SUM_INSURED_RE = re.compile(
    r"(?i)sum\s*insured\s*[:\-]?\s*(?:rs\.?|inr|₹)?\s*([0-9][0-9,]*\.?[0-9]*)"
)
_DATE_ISO_RE = re.compile(r"\b(\d{4}-\d{2}-\d{2})\b")
_DATE_DMY_RE = re.compile(r"\b(\d{1,2}[-\/]\d{1,2}[-\/]\d{2,4})\b")
_PREMIUM_RE = re.compile(
    r"(?i)premium\s*(?:amount)?\s*[:\-]?\s*(?:rs\.?|inr|₹)?\s*([0-9][0-9,]*\.?[0-9]*)"
)
_INSURER_NAMES = (
    "hdfc ergo", "icici lombard", "bajaj allianz", "tata aig",
    "new india assurance", "oriental insurance", "national insurance",
    "united india", "reliance general", "iffco tokio", "sbi general",
    "star health", "manipalcigna", "niva bupa", "aditya birla health",
    "care health", "max bupa", "digit", "acko", "go digit", "zuno",
    "future generali", "cholamandalam", "edelweiss", "kotak general",
    "liberty general", "raheja qbe", "universal sompo", "bharti axa",
    "royal sundaram", "shriram general", "magma hdi",
)


def _first_match(re_obj: re.Pattern, text: str) -> Optional[re.Match]:
    return re_obj.search(text)


def _parse_currency_to_paise(raw: str) -> int:
    """Convert '5,00,000' or '5,00,000.50' to integer paise. INR
    convention is lakh/crore grouping, but the regex matches
    standard Western commas too. Returns 0 on parse failure."""
    cleaned = raw.replace(",", "").strip()
    try:
        rupees = float(cleaned)
        return int(round(rupees * 100))
    except ValueError:
        return 0


def _format_inr(paise: int) -> str:
    """Render paise as Indian-grouped rupees: 50000000 -> ₹5,00,000."""
    rupees = paise // 100
    s = str(rupees)
    if len(s) <= 3:
        return f"₹{s}"
    # Last 3 digits, then groups of 2 from the right
    last_three = s[-3:]
    rest = s[:-3]
    groups = []
    while len(rest) > 2:
        groups.append(rest[-2:])
        rest = rest[:-2]
    if rest:
        groups.append(rest)
    return "₹" + ",".join(reversed(groups)) + "," + last_three


class PolicyNumberExtractor:
    field_name = "policy_number"
    parser_kind = ParserKind.DETERMINISTIC_REGEX

    async def extract(
        self, document_id: UUID, page_texts: dict[int, str]
    ) -> Optional[ExtractorResult]:
        # Prefer page 1 (most policies print the number on page 1)
        for page_num in sorted(page_texts):
            m = _first_match(_POLICY_NUMBER_RE, page_texts[page_num])
            if m:
                raw = m.group(1)
                return ExtractorResult(
                    field_name=self.field_name,
                    value=ExtractedValue(
                        raw=raw, normalized=raw, display=raw,
                    ),
                    value_type=ValueType.STRING,
                    confidence=0.9,
                    page_artifact_id=UUID(int=0),  # filled by pipeline
                    cite_string=f"page {page_num}",
                )
        return None


class PolicyHolderExtractor:
    field_name = "policy_holder_name"
    parser_kind = ParserKind.DETERMINISTIC_REGEX

    async def extract(
        self, document_id: UUID, page_texts: dict[int, str]
    ) -> Optional[ExtractorResult]:
        for page_num in sorted(page_texts):
            m = _first_match(_POLICY_HOLDER_RE, page_texts[page_num])
            if m:
                raw = m.group(1).strip()
                return ExtractorResult(
                    field_name=self.field_name,
                    value=ExtractedValue(
                        raw=raw, normalized=raw, display=raw.title(),
                    ),
                    value_type=ValueType.STRING,
                    confidence=0.85,
                    page_artifact_id=UUID(int=0),
                    cite_string=f"page {page_num}",
                )
        return None


class SumInsuredExtractor:
    field_name = "sum_insured"
    parser_kind = ParserKind.DETERMINISTIC_REGEX

    async def extract(
        self, document_id: UUID, page_texts: dict[int, str]
    ) -> Optional[ExtractorResult]:
        for page_num in sorted(page_texts):
            m = _first_match(_SUM_INSURED_RE, page_texts[page_num])
            if m:
                raw = m.group(1)
                paise = _parse_currency_to_paise(raw)
                if paise <= 0:
                    continue
                return ExtractorResult(
                    field_name=self.field_name,
                    value=ExtractedValue(
                        raw=raw, normalized=paise, display=_format_inr(paise),
                    ),
                    value_type=ValueType.CURRENCY,
                    confidence=0.95,
                    page_artifact_id=UUID(int=0),
                    cite_string=f"page {page_num}",
                )
        return None


class PolicyStartDateExtractor:
    field_name = "policy_start_date"
    parser_kind = ParserKind.DETERMINISTIC_REGEX

    async def extract(
        self, document_id: UUID, page_texts: dict[int, str]
    ) -> Optional[ExtractorResult]:
        for page_num in sorted(page_texts):
            text = page_texts[page_num]
            m = _first_match(_DATE_ISO_RE, text) or _first_match(
                _DATE_DMY_RE, text
            )
            if m:
                raw = m.group(1)
                # Try to normalize; fall back to raw
                normalized = raw
                try:
                    if "-" in raw and len(raw) == 10:
                        normalized = raw
                    else:
                        # DMY -> assume DD/MM/YYYY for Indian policies
                        parts = re.split(r"[-\/]", raw)
                        if len(parts) == 3:
                            d, mo, y = parts
                            if len(y) == 2:
                                y = "20" + y
                            normalized = f"{y}-{int(mo):02d}-{int(d):02d}"
                except (ValueError, IndexError):
                    normalized = raw
                return ExtractorResult(
                    field_name=self.field_name,
                    value=ExtractedValue(
                        raw=raw, normalized=normalized, display=normalized,
                    ),
                    value_type=ValueType.DATE,
                    confidence=0.8,
                    page_artifact_id=UUID(int=0),
                    cite_string=f"page {page_num}",
                )
        return None


