-- ============================================================================
-- user_lifecycle: one row per user_uid, current lifecycle state
-- ============================================================================
create table if not exists public.user_lifecycle (
  user_uid text primary key,
  identity_type text not null check (identity_type in ('anonymous', 'account')),
  current_stage text not null check (current_stage in (
    'visitor', 'install', 'anonymous', 'account', 'activated',
    'power_user', 'paywall_viewer', 'paying', 'retained_paying',
    'churned', 'evangelist', 'stalled_power_user', 'at_risk', 'archived'
  )),
  stage_entered_at timestamptz not null default now(),
  engagement_score smallint not null default 0 check (engagement_score between 0 and 100),
  install_id uuid,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  archived_at timestamptz
);

create index if not exists idx_user_lifecycle_stage
  on public.user_lifecycle (current_stage);
create index if not exists idx_user_lifecycle_score
  on public.user_lifecycle (engagement_score desc);
create index if not exists idx_user_lifecycle_last_seen
  on public.user_lifecycle (last_seen_at desc);

alter table public.user_lifecycle enable row level security;

revoke all on table public.user_lifecycle from public, anon, authenticated;
grant select, insert, update, delete on table public.user_lifecycle to service_role;

comment on table public.user_lifecycle is
  'Per-user lifecycle stage and engagement score. One row per user_uid. Service-role only.';


-- ============================================================================
-- subscriptions: one row per provider subscription, current state
-- ============================================================================
create table if not exists public.subscriptions (
  subscription_id uuid primary key,
  owner_id text not null,
  billing_provider text not null check (billing_provider in ('dodo', 'razorpay')),
  provider_subscription_id text not null,
  created_via text not null default 'direct' check (created_via in ('direct', 'fallback')),
  plan_id text not null,
  plan_amount_paise bigint not null check (plan_amount_paise >= 0),
  currency text not null default 'INR',
  started_at timestamptz not null,
  current_period_start timestamptz not null,
  current_period_end timestamptz not null,
  cancelled_at timestamptz,
  cancellation_reason_bucket text check (cancellation_reason_bucket in (
    'too_expensive', 'no_value', 'switched_apps', 'privacy', 'other'
  )),
  expired_at timestamptz,
  grace_period_end timestamptz,
  status text not null check (status in (
    'active', 'past_due', 'cancelled', 'expired', 'in_grace'
  )),
  unique (billing_provider, provider_subscription_id)
);

create index if not exists idx_subscriptions_owner
  on public.subscriptions (owner_id);
create index if not exists idx_subscriptions_status
  on public.subscriptions (status);
create index if not exists idx_subscriptions_period_end
  on public.subscriptions (current_period_end)
  where status = 'active';
create index if not exists idx_subscriptions_provider
  on public.subscriptions (billing_provider);

alter table public.subscriptions enable row level security;

revoke all on table public.subscriptions from public, anon, authenticated;
grant select, insert, update, delete on table public.subscriptions to service_role;

comment on table public.subscriptions is
  'Canonical subscription state across Dodo + Razorpay. Provider-scoped UNIQUE prevents double-booking. Service-role only.';


