-- ============================================================================
-- profiles.role: add operator role for RLS-based operator auth (Phase R1.9)
-- ============================================================================
-- This depends on a `profiles` table existing. The canonical plan calls for one
-- (per docs/planning/coverwise_supabase_canonical_plan_2026-07-16.md §"Product
-- and ownership data") but it is not in 001_coverwise_schema.sql yet. This
-- migration creates it if missing, and adds the role column.

create table if not exists public.profiles (
  user_uid text primary key,
  email text,
  display_name text,
  role text not null default 'user' check (role in ('user', 'operator')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

-- Users can read their own profile.
-- Postgres does not support CREATE POLICY IF NOT EXISTS, so we guard with a DO block.
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'profiles'
      and policyname = 'Users read own profile'
  ) then
    create policy "Users read own profile"
      on public.profiles
      for select
      using (user_uid = auth.jwt() ->> 'sub');
  end if;
end
$$;

-- Service-role has full access (no policy needed for service_role bypasses RLS by default).
revoke all on table public.profiles from public, anon, authenticated;
grant select, insert, update on table public.profiles to authenticated;
grant select, insert, update, delete on table public.profiles to service_role;

comment on table public.profiles is
  'Per-user account metadata. role column gates operator-only access. Users can read their own row.';
