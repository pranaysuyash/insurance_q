def write_arb(name: str, data: dict) -> None:
    path = L10N_DIR / name
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write('\n')
    print(f'Wrote {path} ({len(data)} keys)')


